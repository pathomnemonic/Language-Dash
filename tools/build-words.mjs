// Builds the runtime word tables (js/lang/data/*.js) from the editable sources:
//   data/concepts.json        the 1,000 core concepts (id, en, pos, cat, sense), most common first
//   data/words/<code>.json    for each non-English language: 1,000 entries aligned with concepts, [word] or [word, romanization]
// English is derived from concepts.json. Run: node tools/build-words.mjs   (it also validates; exits 1 on any problem)
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CODES = ['en', 'es', 'fr', 'de', 'it', 'pt', 'nl', 'sv', 'pl', 'ru', 'ja', 'ko', 'zh', 'ar', 'hi'];
const ROMAN = new Set(['ru', 'ja', 'ko', 'zh', 'ar', 'hi']);
const only = (process.argv.find((a) => a.startsWith('--only=')) || '').slice(7);
const outDir = resolve(root, 'js/lang/data');
mkdirSync(outDir, { recursive: true });

const concepts = JSON.parse(readFileSync(resolve(root, 'data/concepts.json'), 'utf8'));
let problems = 0;
const bad = (m) => { problems++; if (problems <= 80) console.error('✖ ' + m); };
if (concepts.length < 1000) bad('concepts.json must have at least 1000 entries, has ' + concepts.length);
const BASE = 1000; // every language covers at least the first 1,000 concepts; en/es/fr can cover all of them

const key = (s) => String(s).normalize('NFC').toLowerCase().replace(/[^\p{L}\p{M}\p{N}]+/gu, '');
const MAX_SHARED = 60; // a few genuine overlaps (why/because, one verb for two senses) are fine; more means weak word choices
const header = (what) => '// GENERATED by tools/build-words.mjs from data/. Do not edit by hand.\n// ' + what + '\n';

writeFileSync(resolve(outDir, 'concepts.js'), header('[category, part of speech] per concept, index = id - 1') +
  'export default ' + JSON.stringify(concepts.map((c) => [c.cat, c.pos])) + ';\n');

for (const code of CODES) {
  if (only && code !== only) continue;
  let entries;
  if (code === 'en') {
    entries = concepts.map((c) => (c.sense ? [c.en, '', c.sense] : [c.en]));
  } else {
    const file = resolve(root, 'data/words/' + code + '.json');
    if (!existsSync(file)) { console.warn('… no data for ' + code + ' yet, skipped'); continue; }
    entries = JSON.parse(readFileSync(file, 'utf8'));
    if (!Array.isArray(entries) || (entries.length !== BASE && entries.length !== concepts.length)) { bad(code + ': needs ' + BASE + ' or ' + concepts.length + ' entries, has ' + (entries && entries.length)); continue; }
    entries = entries.map((e) => (Array.isArray(e) ? e : [e]));
  }
  const seen = new Map();
  let shared = 0;
  const keyOf = (w, i) => key(w) + (code === 'en' ? '|' + (concepts[i].sense || '') : '');
  entries.forEach((e, i) => {
    const w = e[0];
    if (typeof w !== 'string' || !w.trim()) return bad(code + ' #' + (i + 1) + ' (' + concepts[i].en + '): empty word');
    if (/\s/.test(w.trim()) && code !== 'en') bad(code + ' #' + (i + 1) + ' (' + concepts[i].en + '): "' + w + '" has a space (one word only)');
    if (w !== w.trim() || /[()/,;]/.test(w)) bad(code + ' #' + (i + 1) + ' (' + concepts[i].en + '): "' + w + '" has stray punctuation');
    if (ROMAN.has(code) && !(typeof e[1] === 'string' && e[1].trim())) bad(code + ' #' + (i + 1) + ' (' + concepts[i].en + '): missing romanization');
    const k = keyOf(w, i);
    if (seen.has(k)) {
      if (code === 'en') bad(code + ': "' + w + '" used twice with the same sense (#' + (seen.get(k) + 1) + ', #' + (i + 1) + ')');
      else { shared++; console.warn('~ ' + code + ': "' + w + '" is both #' + (seen.get(k) + 1) + ' (' + concepts[seen.get(k)].en + ') and #' + (i + 1) + ' (' + concepts[i].en + ')'); }
    } else seen.set(k, i);
  });
  if (shared > Math.max(MAX_SHARED, Math.round(entries.length * 0.06))) bad(code + ': ' + shared + ' words are shared by two concepts (max ' + MAX_SHARED + '): use the natural word for each concept, not a rare substitute');
  writeFileSync(resolve(outDir, code + '.js'), header(code + ': [word, romanization?, sense?] per concept') + 'export default ' + JSON.stringify(entries) + ';\n');
}
if (problems) { console.error('\n' + problems + ' problem(s)'); process.exit(1); }
console.log('word tables built');
